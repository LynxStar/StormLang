namespace Storm.SourceGenerator.Emit;

/// <summary>
/// Emits AST node types and Storm.Runtime support types.
/// Generates one type per rule: sealed record for single-alternative rules,
/// abstract record + sealed subtypes for rules with named alternatives.
/// </summary>
public static partial class AstEmitter
{
    /// <summary>
    /// Generates the Storm.Runtime types source file (Token, TokenChannel,
    /// SourceSpan, SyntaxNode, etc.).
    /// </summary>
    public static string EmitRuntimeTypes(string originType = "object")
    {
        var writer = new CodeWriter();

        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteEmptyLine();
        writer.WriteLine("using System;");
        writer.WriteLine("using System.Collections.Generic;");
        writer.WriteLine("using System.Collections.Immutable;");
        writer.WriteLine("using System.Linq;");
        writer.WriteEmptyLine();

        writer.WriteBlock("namespace Storm.Runtime", () =>
        {
            // TokenChannel enum
            writer.WriteBlock("public enum TokenChannel", () =>
            {
                writer.WriteLine("Default,");
                writer.WriteLine("Hidden,");
            });
            writer.WriteEmptyLine();

            // SourceSpan
            writer.WriteBlock("public readonly struct SourceSpan", () =>
            {
                writer.WriteLine("public int Start { get; }");
                writer.WriteLine("public int Length { get; }");
                writer.WriteLine("public int End => Start + Length;");
                writer.WriteEmptyLine();
                writer.WriteBlock("public SourceSpan(int start, int length)", () =>
                {
                    writer.WriteLine("Start = start;");
                    writer.WriteLine("Length = length;");
                });
            });
            writer.WriteEmptyLine();

            // LinePosition
            writer.WriteBlock("public readonly struct LinePosition", () =>
            {
                writer.WriteLine("public int Line { get; }");
                writer.WriteLine("public int Column { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public LinePosition(int line, int column)", () =>
                {
                    writer.WriteLine("Line = line;");
                    writer.WriteLine("Column = column;");
                });
            });
            writer.WriteEmptyLine();

            // Token
            writer.WriteBlock("public readonly struct Token", () =>
            {
                writer.WriteLine("public int Kind { get; }");
                writer.WriteLine("public SourceSpan Span { get; }");
                writer.WriteLine("public LinePosition Start { get; }");
                writer.WriteLine("public LinePosition End { get; }");
                writer.WriteLine("public TokenChannel Channel { get; }");
                writer.WriteLine("public string Lexeme { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public Token(int kind, SourceSpan span, LinePosition start, LinePosition end, TokenChannel channel, string lexeme)", () =>
                {
                    writer.WriteLine("Kind = kind;");
                    writer.WriteLine("Span = span;");
                    writer.WriteLine("Start = start;");
                    writer.WriteLine("End = end;");
                    writer.WriteLine("Channel = channel;");
                    writer.WriteLine("Lexeme = lexeme;");
                });
            });
            writer.WriteEmptyLine();

            // SourceText (simple wrapper for generated code to reference)
            writer.WriteBlock("public class SourceText", () =>
            {
                writer.WriteLine("public string Path { get; }");
                writer.WriteLine("public string Contents { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public SourceText(string path, string contents)", () =>
                {
                    writer.WriteLine("Path = path;");
                    writer.WriteLine("Contents = contents;");
                });
            });
            writer.WriteEmptyLine();

            // DiagnosticEntry (structured diagnostic entry for generated code)
            writer.WriteBlock("public readonly struct DiagnosticEntry", () =>
            {
                writer.WriteLine("public string Message { get; }");
                writer.WriteLine("public string? FilePath { get; }");
                writer.WriteLine("public int Line { get; }");
                writer.WriteLine("public int Column { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public DiagnosticEntry(string message, string? filePath, int line, int column)", () =>
                {
                    writer.WriteLine("Message = message;");
                    writer.WriteLine("FilePath = filePath;");
                    writer.WriteLine("Line = line;");
                    writer.WriteLine("Column = column;");
                });
            });
            writer.WriteEmptyLine();

            // DiagnosticBag (structured collection for generated code)
            writer.WriteBlock("public class DiagnosticBag", () =>
            {
                writer.WriteLine("private readonly System.Collections.Generic.List<DiagnosticEntry> _entries = new System.Collections.Generic.List<DiagnosticEntry>();");
                writer.WriteEmptyLine();
                writer.WriteBlock("public void Add(string message, string? filePath, int line, int column)", () =>
                    writer.WriteLine("_entries.Add(new DiagnosticEntry(message, filePath, line, column));"));
                writer.WriteEmptyLine();
                writer.WriteBlock("public void Add(string message)", () =>
                    writer.WriteLine("_entries.Add(new DiagnosticEntry(message, null, 0, 0));"));
                writer.WriteEmptyLine();
                writer.WriteLine("public bool HasErrors => _entries.Count > 0;");
                writer.WriteLine("public int Count => _entries.Count;");
                writer.WriteLine("public System.Collections.Generic.IReadOnlyList<DiagnosticEntry> Entries => _entries;");
                writer.WriteLine("public System.Collections.Generic.IReadOnlyList<string> Messages => _entries.Select(e => e.Message).ToList();");
                writer.WriteEmptyLine();
                writer.WriteBlock("public void TruncateTo(int count)", () => writer.WriteBlock("if (count >= 0 && count < _entries.Count)", () =>
                        writer.WriteLine("_entries.RemoveRange(count, _entries.Count - count);")));
            });
            writer.WriteEmptyLine();

            // StormRuntimeDiagnostic (simple diagnostic for generated lexer/parser)
            writer.WriteBlock("public class StormRuntimeDiagnostic", () =>
            {
                writer.WriteLine("public string Message { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public StormRuntimeDiagnostic(string message)", () => writer.WriteLine("Message = message;"));
            });
            writer.WriteEmptyLine();

            // TokenStream
            writer.WriteBlock("public class TokenStream", () =>
            {
                writer.WriteLine("public SourceText Source { get; }");
                writer.WriteLine("public ImmutableArray<Token> AllTokens { get; }");
                writer.WriteLine("public ImmutableArray<Token> DefaultChannelTokens { get; }");
                writer.WriteEmptyLine();
                writer.WriteBlock("public TokenStream(SourceText source, ImmutableArray<Token> tokens)", () =>
                {
                    writer.WriteLine("Source = source;");
                    writer.WriteLine("AllTokens = tokens;");
                    writer.WriteLine("var defaultBuilder = ImmutableArray.CreateBuilder<Token>();");
                    writer.WriteBlock("foreach (var token in tokens)", () => writer.WriteBlock("if (token.Channel == TokenChannel.Default)", () => writer.WriteLine("defaultBuilder.Add(token);")));
                    writer.WriteLine("DefaultChannelTokens = defaultBuilder.ToImmutable();");
                });
            });
            writer.WriteEmptyLine();

            // SyntaxNode base
            writer.WriteBlock("public abstract class SyntaxNode", () =>
            {
                writer.WriteLine("public SourceSpan Span { get; set; }");
                writer.WriteLine("public SyntaxNode? Parent { get; set; }");
                writer.WriteLine($"public {originType}? Origin {{ get; set; }}");
                writer.WriteLine("public ImmutableArray<Token> LeadingHiddenTokens { get; set; } = ImmutableArray<Token>.Empty;");
                writer.WriteLine("public ImmutableArray<Token> TrailingHiddenTokens { get; set; } = ImmutableArray<Token>.Empty;");
                writer.WriteEmptyLine();
                writer.WriteLine("public abstract IEnumerable<SyntaxNode> Children();");
                writer.WriteEmptyLine();
                writer.WriteLine("/// <summary>");
                writer.WriteLine("/// Walks the tree rooted at this node and sets the Parent property on all descendants.");
                writer.WriteLine("/// Call once after parsing to enable upward traversal.");
                writer.WriteLine("/// </summary>");
                writer.WriteBlock("public void SetParentLinks()", () => writer.WriteBlock("foreach (var child in Children())", () => writer.WriteBlock("if (child is not null)", () =>
                        {
                            writer.WriteLine("child.Parent = this;");
                            writer.WriteLine("child.SetParentLinks();");
                        })));
            });
        });

        return writer.ToString();
    }

    /// <summary>
    /// Generates the AST node types source file for the consumer grammar.
    /// </summary>
    public static string EmitAstNodes(EmissionContext context)
    {
        var writer = new CodeWriter();

        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteEmptyLine();
        writer.WriteLine("using System;");
        writer.WriteLine("using System.Collections.Generic;");
        writer.WriteLine("using System.Collections.Immutable;");

        // The obsolete list shims (e.g. Multiplicatives) forward through LINQ's
        // Select/ToImmutableArray, so import System.Linq only when such a shim is
        // actually emitted -- this keeps the generated file free of an unused using
        // when shims are disabled or no list shim is produced.
        if(AstFileUsesLinq(context))
        {
            writer.WriteLine("using System.Linq;");
        }

        writer.WriteLine("using Storm.Runtime;");
        writer.WriteEmptyLine();

        writer.WriteBlock($"namespace {context.ConsumerNamespace}", () =>
        {
            var first = true;
            foreach(var rule in context.Grammar.Rules)
            {
                if(!first)
                {
                    writer.WriteEmptyLine();
                }

                first = false;

                EmitRuleNodeTypes(writer, rule, context);
            }

            // Emit trait interfaces after all node classes
            foreach(var trait in context.Traits)
            {
                writer.WriteEmptyLine();
                EmitTraitInterface(writer, trait);
            }
        });

        return writer.ToString();
    }

    /// <summary>
    /// Returns true when the emitted AST file will contain an obsolete list shim,
    /// which forwards through LINQ (<c>Select(...).ToImmutableArray()</c>). A list
    /// shim is produced only for a rule reference inside a <c>*</c>/<c>+</c>
    /// struct-projected group, and only when shims are enabled. Used to decide
    /// whether the generated file needs a <c>using System.Linq;</c> directive.
    /// </summary>
    private static bool AstFileUsesLinq(EmissionContext context)
    {
        if(!context.EmitObsoleteShims)
        {
            return false;
        }

        foreach(var rule in context.Grammar.Rules)
        {
            foreach(var alt in rule.Alternatives)
            {
                foreach(var group in DetectAnonymousGroups(alt))
                {
                    if(group.Modifier is GroupModifier.ZeroOrMore or GroupModifier.OneOrMore
                        && group.Sequence.Elements.Any(element => element is RuleRefIR))
                    {
                        return true;
                    }
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Emits the AST node type(s) for a single rule.
    /// </summary>
    private static void EmitRuleNodeTypes(CodeWriter writer, RuleIR rule, EmissionContext context)
    {
        if(HasSharedAlternativeNode(rule))
        {
            EmitSealedNode(writer, rule, context);
        }
        else
        {
            EmitAbstractNodeWithSubtypes(writer, rule, context);
        }
    }

    /// <summary>
    /// Emits a sealed record for a single-alternative rule (or a rule with no named alternatives).
    /// </summary>
    private static void EmitSealedNode(CodeWriter writer, RuleIR rule, EmissionContext context)
    {
        var nodeTypeName = rule.Name + "Node";
        var baseType = "SyntaxNode";
        var shapes = CollectNodeShapes(rule, nodeTypeName, context.EmitObsoleteShims, out var groupStructs, out var shims);
        var properties = shapes.SelectMany(shape => shape.Properties).GroupBy(property => property.Name).Select(group => group.First()).ToList();

        // Check for trait interfaces
        var interfaces = new List<string>();
        if(context.RuleTraitBindings.TryGetValue(rule.Name, out var traits))
        {
            foreach(var trait in traits)
            {
                var interfaceName = $"I{trait.Name}Node";
                if(!interfaces.Contains(interfaceName))
                {
                    interfaces.Add(interfaceName);
                }
            }
        }

        var implementsList = interfaces.Count > 0
            ? $"{baseType}, {string.Join(", ", interfaces)}"
            : baseType;

        writer.WriteBlock($"public sealed class {nodeTypeName} : {implementsList}", () =>
        {
            if(shapes.Count > 1)
            {
                writer.WriteLine("internal int __StormAlternative { get; set; }");
            }

            // Properties
            foreach(var prop in properties)
            {
                writer.WriteLine($"public {prop.TypeName} {prop.Name} {{ get; set; }}{prop.DefaultValue}");
            }

            if(properties.Count > 0)
            {
                writer.WriteEmptyLine();
            }

            // Obsolete migration shims (Task 5.1)
            EmitObsoleteShimProperties(writer, shims);

            // Children() override
            EmitAlternativeChildren(writer, shapes);
        });

        // Emit anonymous group structs as sibling types in the same namespace (Task 3.1).
        foreach(var groupStruct in groupStructs)
        {
            writer.WriteEmptyLine();
            EmitGroupStruct(writer, groupStruct);
        }
    }

    /// <summary>
    /// Emits an abstract record + sealed subtypes for rules with named alternatives.
    /// </summary>
    private static void EmitAbstractNodeWithSubtypes(CodeWriter writer, RuleIR rule, EmissionContext context)
    {
        var baseNodeTypeName = rule.Name + "Node";

        // Abstract base
        writer.WriteBlock($"public abstract class {baseNodeTypeName} : SyntaxNode", () =>
        {
        });

        // Sealed subtypes for each named alternative
        foreach(var alt in rule.Alternatives)
        {
            if(alt.Expression is InlineBlockIR inlineBlock)
            {
                // Expand inline block arms into individual sealed node classes.
                // Do NOT emit a wrapper node for the inline block itself.
                foreach(var arm in inlineBlock.Arms)
                {
                    writer.WriteEmptyLine();
                    EmitInlineArmNode(writer, rule, arm);
                }
            }
            else
            {
                writer.WriteEmptyLine();

                var altName = alt.AlternativeName ?? "Default";
                var subtypeName = altName + rule.Name + "Node";
                var properties = CollectProperties(alt, subtypeName, context.EmitObsoleteShims, out var groupStructs, out var shims);

                // Check for per-alternative trait interfaces
                var interfaces = new List<string>();
                var altKey = $"{rule.Name}.{altName}";
                if(context.RuleTraitBindings.TryGetValue(altKey, out var traits))
                {
                    foreach(var trait in traits)
                    {
                        var interfaceName = $"I{trait.Name}Node";
                        if(!interfaces.Contains(interfaceName))
                        {
                            interfaces.Add(interfaceName);
                        }
                    }
                }

                var implementsList = interfaces.Count > 0
                    ? $"{baseNodeTypeName}, {string.Join(", ", interfaces)}"
                    : baseNodeTypeName;

                EmitSealedSubtype(writer, subtypeName, implementsList, properties, groupStructs, shims);
            }
        }
    }

    /// <summary>
    /// Emits a sealed node class for a single arm of an inline block.
    /// The inline keyword is purely a parse-time optimization — the AST shape
    /// is identical to what a standalone <c>label:TargetRule as AltName</c>
    /// alternative would produce: a single property named from the arm's label,
    /// of type <c>{TargetRule}Node</c>.
    /// </summary>
    private static void EmitInlineArmNode(CodeWriter writer, RuleIR rule, InlineArmIR arm)
    {
        var baseNodeTypeName = rule.Name + "Node";
        var subtypeName = arm.AlternativeName + rule.Name + "Node";

        // Treat this arm as if it were `label:TargetRule as AltName` —
        // produce a single property pointing to the target rule's node.
        var propName = PascalCase(arm.Label ?? arm.TargetRule.Name);
        var targetNodeType = arm.TargetRule.Name + "Node";
        var properties = new List<PropertyInfo>
        {
            new(propName, targetNodeType, false, true, false, " = default!;")
        };

        // Inline arm nodes carry a single rule-ref property and never project
        // anonymous groups, so no group structs or obsolete shims are emitted for them.
        EmitSealedSubtype(writer, subtypeName, baseNodeTypeName, properties, new List<GroupStructModel>(), new List<ObsoleteShim>());
    }


    /// <summary>
    /// Emits a sealed subtype class with the given properties, obsolete migration
    /// shims, and Children() override, followed by any anonymous group structs as
    /// sibling types.
    /// </summary>
    private static void EmitSealedSubtype(CodeWriter writer, string subtypeName, string implementsList, List<PropertyInfo> properties, List<GroupStructModel> groupStructs, List<ObsoleteShim> shims)
    {
        writer.WriteBlock($"public sealed class {subtypeName} : {implementsList}", () =>
        {
            // Properties
            foreach(var prop in properties)
            {
                writer.WriteLine($"public {prop.TypeName} {prop.Name} {{ get; set; }}{prop.DefaultValue}");
            }

            if(properties.Count > 0)
            {
                writer.WriteEmptyLine();
            }

            // Obsolete migration shims (Task 5.1)
            EmitObsoleteShimProperties(writer, shims);

            // Children() override
            EmitChildrenOverride(writer, properties);
        });

        // Emit anonymous group structs as sibling types in the same namespace (Task 3.1).
        foreach(var groupStruct in groupStructs)
        {
            writer.WriteEmptyLine();
            EmitGroupStruct(writer, groupStruct);
        }
    }

    /// <summary>
    /// Emits the <c>[Obsolete]</c> migration shim properties for a node class (Task
    /// 5.1). Each shim is an expression-bodied property carrying an
    /// <c>[Obsolete("Use Group{N}")]</c> attribute and forwarding to the new group
    /// data. Emits nothing (and no separating blank line) when there are no shims,
    /// so a node without struct-projected groups -- or output produced with shims
    /// disabled -- is byte-for-byte unchanged.
    /// </summary>
    private static void EmitObsoleteShimProperties(CodeWriter writer, List<ObsoleteShim> shims)
    {
        if(shims.Count == 0)
        {
            return;
        }

        foreach(var shim in shims)
        {
            writer.WriteLine($"[Obsolete(\"Use {shim.GroupPropertyName}\")]");
            writer.WriteLine($"public {shim.TypeName} {shim.PropertyName} => {shim.Body};");
        }

        writer.WriteEmptyLine();
    }

    /// <summary>
    /// Collects the properties for an alternative's AST node type and, via
    /// <paramref name="groupStructs"/>, the anonymous group structs that must be
    /// emitted as sibling types.
    /// </summary>
    /// <remarks>
    /// Anonymous-group scoping rule (Requirement 6 / Property 7): a parenthesised
    /// subexpression is projected as a group struct only when
    /// <see cref="DetectAnonymousGroups"/> reports it -- that is, when a repetition or
    /// optional wraps a sequence with two or more value-bearing elements (a labelled
    /// element or an unlabelled rule reference; bare fixed tokens are structural and
    /// do not count). A group with fewer than two value-bearing elements is not
    /// detected and keeps its existing scalar/list/optional promotion, so
    /// backward-compatibility holds in every direction:
    /// <list type="bullet">
    ///   <item>Two value-bearing elements such as <c>(operator:(PLUS | MINUS)
    ///         right:Multiplicative)*</c> (the <c>Additive</c>/<c>Equality</c>
    ///         family) are detected and produce a struct.</item>
    ///   <item>Single value-bearing groups such as <c>(COMMA rest:Expression)*</c>,
    ///         <c>(COMMA Param)*</c>, or <c>(EQ Expr)?</c> keep their existing list or
    ///         optional property.</item>
    ///   <item>Token-only groups such as <c>(DOT IDENT)*</c> have zero value-bearing
    ///         elements and keep the existing lone-token promotion.</item>
    ///   <item>A label on the whole group such as <c>init:(EQ Expr)?</c> points at the
    ///         optional/repetition wrapper -- not at anything inside -- and does not
    ///         change the count, so it keeps its existing behaviour.</item>
    /// </list>
    /// </remarks>
    private static List<PropertyInfo> CollectProperties(RuleAlternativeIR alt, string nodeTypeName, bool emitObsoleteShims, out List<GroupStructModel> groupStructs, out List<ObsoleteShim> shims, Func<AnonymousGroupInfo, string>? groupName = null)
    {
        var properties = new List<PropertyInfo>();
        groupStructs = new List<GroupStructModel>();
        shims = new List<ObsoleteShim>();
        var usedNames = new HashSet<string>();

        // Detect anonymous groups up front (committed wave-0 logic). Their labels
        // move onto the group struct (or the collapsed pure-token property), and
        // their repetition/optional wrapper must not also emit an auto-generated
        // list/optional property on the parent.
        var groups = DetectAnonymousGroups(alt);

        var inGroupLabels = new HashSet<FieldLabelIR>();
        var groupSequences = new HashSet<ExpressionIR>();
        foreach(var group in groups)
        {
            _ = groupSequences.Add(group.Sequence);
            foreach(var label in group.Labels)
            {
                _ = inGroupLabels.Add(label);
            }
        }

        // Build a set of TokenRefIR expressions that live inside a ZeroOrMoreIR
        // or OneOrMoreIR so we can promote labeled tokens to list properties.
        // Only tokens need this — rule refs inside repetitions already get a
        // separate ImmutableArray property via the unlabeled-property walk.
        var tokensInsideRepetition = new HashSet<ExpressionIR>();
        CollectTokensInsideRepetition(alt.Expression, false, tokensInsideRepetition);

        // Build a set of expressions that live inside an OptionalIR so we can
        // make labeled token fields nullable (Token?) when they may not be set.
        var exprsInsideOptional = new HashSet<ExpressionIR>();
        CollectExpressionsInsideOptional(alt.Expression, false, exprsInsideOptional);

        // Build a set of AlternationIR expressions that live inside a ZeroOrMoreIR or
        // OneOrMoreIR. A label on a *pure-token* alternation here (the sole
        // value-bearing element of a starred group, e.g. (op:(PLUS | MINUS))*) is not
        // struct-projected, so it must be promoted to an ImmutableArray<Token> on the
        // parent instead of being flattened to a scalar Token that drops the
        // repetition. The pure-token gate is applied at the use site.
        var alternationsInsideRepetition = new HashSet<ExpressionIR>();
        CollectAlternationsInsideRepetition(alt.Expression, false, alternationsInsideRepetition);

        var repeatedRuleRefs = new HashSet<RuleRefIR>();
        CollectRepeatedRuleRefs(alt.Expression, repeatedRuleRefs);

        var insideRepetition = new HashSet<ExpressionIR>();
        CollectInside(alt.Expression, expr => expr is ZeroOrMoreIR or OneOrMoreIR, false, insideRepetition);

        // First, add properties from field labels. Labels that live inside an
        // anonymous group are excluded here — they become fields on the group
        // struct (or the collapsed pure-token property) instead (Task 3.4).
        foreach(var label in alt.FieldLabels)
        {
            if(inGroupLabels.Contains(label))
            {
                continue;
            }

            var propName = PascalCase(label.Label);
            propName = EnsureUnique(propName, usedNames);
            PropertyInfo propInfo;
            if(tokensInsideRepetition.Contains(label.Expression))
            {
                // The labeled token is inside a * or + repetition — generate a list property
                propInfo = new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;").FilledBy(label.Expression, true);
            }
            else if(alternationsInsideRepetition.Contains(label.Expression)
                && IsPureTokenAlternation(new List<FieldLabelIR> { label }))
            {
                // A labeled lone pure-token alternation inside a * or + repetition, e.g.
                // (op:(PLUS | MINUS))*. It carries one value-bearing element, so it is not
                // struct-projected (struct-group labels are excluded above via
                // inGroupLabels); promote it to a token list on the parent, mirroring the
                // bare-token promotion above (design Property 5). A mixed alternation fails
                // the pure-token gate and falls through to its existing scalar promotion.
                propInfo = new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;").FilledBy(label.Expression, true);
            }
            else if(exprsInsideOptional.Contains(label.Expression))
            {
                // The labeled expression is inside an optional group — make it nullable
                propInfo = (GetPropertyInfo(label.Expression, propName) switch
                {
                    var p when p.TypeName == "Token" => new PropertyInfo(propName, "Token?", true, false, false, ""),
                    var p when !p.IsNullable && p.IsNodeType => new PropertyInfo(propName, p.TypeName + "?", true, true, false, ""),
                    var p => p,
                }).FilledBy(label.Expression, false);
            }
            else if(label.Expression is RuleRefIR repeated && repeatedRuleRefs.Contains(repeated))
            {
                // Kept beside the list only because consumers still read it (backlog/storm.md).
                propInfo = new PropertyInfo(propName, repeated.Rule.Name + "Node", false, true, false, " = default!;").FilledBy(repeated, false, child: false);
            }
            else
            {
                var appends = label.Expression is RuleRefIR or OptionalIR && insideRepetition.Contains(label.Expression);
                var source = Representative(label.Expression, groupSequences);
                propInfo = (appends ? RepeatedLabelProperty(label.Expression, propName) : GetPropertyInfo(label.Expression, propName))
                    .FilledBy(source, appends || label.Expression is ZeroOrMoreIR or OneOrMoreIR, !Forwards(label.Expression, source, alt.FieldLabels, groupSequences, repeatedRuleRefs));
            }

            properties.Add(propInfo);
        }

        // Next, project each anonymous group: either a collapsed pure-token property
        // or a Group{N} property backed by a generated struct (Tasks 3.1-3.3, 4.1-4.2).
        // When shims are enabled, each struct-projected group also contributes the
        // old flat-field properties as [Obsolete] shims (Tasks 5.1-5.4).
        foreach(var group in groups)
        {
            AddGroupProjection(group, nodeTypeName, properties, groupStructs, shims, emitObsoleteShims, usedNames, groupName?.Invoke(group));
        }

        // Then, walk the expression to find unlabeled elements. Skip the wrapper
        // expressions that became anonymous groups so we don't also emit their old
        // auto-generated list/optional property (e.g. the redundant Multiplicatives
        // list that used to sit alongside the projected Group0).
        CollectUnlabeledProperties(alt.Expression, alt.FieldLabels, properties, usedNames, groupSequences);

        // A property an alternative may leave unset keeps the non-nullable type its readers were written against, so
        // Children() guards it rather than the type admitting it.
        var skippable = new HashSet<ExpressionIR>();
        CollectInside(alt.Expression, expr => expr is OptionalIR or ZeroOrMoreIR, false, skippable);
        foreach(var property in properties.Where(property => property.IsNodeType && !property.IsList && !property.IsNullable))
        {
            property.MayBeAbsent = property.Source != null && skippable.Contains(property.Source);
        }

        var order = new Dictionary<ExpressionIR, int>();
        CaptureOrder(alt.Expression, order);
        return properties.OrderBy(property => property.Source != null && order.TryGetValue(property.Source, out var position) ? position : int.MaxValue).ToList();
    }

    /// <summary>
    /// Recursively walks the expression tree and adds all <see cref="TokenRefIR"/>
    /// sub-expressions that are nested inside a <see cref="ZeroOrMoreIR"/> or
    /// <see cref="OneOrMoreIR"/> to the <paramref name="result"/> set.
    /// Only tokens need promotion — rule refs already get separate list properties.
    /// </summary>
    private static void CollectTokensInsideRepetition(ExpressionIR expr, bool insideRep, HashSet<ExpressionIR> result)
    {
        if(insideRep && expr is TokenRefIR)
        {
            _ = result.Add(expr);
        }

        switch(expr)
        {
            case SequenceIR seq:
                foreach(var elem in seq.Elements)
                {
                    CollectTokensInsideRepetition(elem, insideRep, result);
                }

                break;
            case AlternationIR alt:
                foreach(var a in alt.Alternatives)
                {
                    CollectTokensInsideRepetition(a, insideRep, result);
                }

                break;
            case OptionalIR opt:
                CollectTokensInsideRepetition(opt.Inner, insideRep, result);
                break;
            case ZeroOrMoreIR zom:
                CollectTokensInsideRepetition(zom.Inner, true, result);
                break;
            case OneOrMoreIR oom:
                CollectTokensInsideRepetition(oom.Inner, true, result);
                break;
        }
    }

    /// <summary>
    /// Recursively walks the expression tree and adds all sub-expressions that
    /// are nested inside an <see cref="OptionalIR"/> to the <paramref name="result"/> set.
    /// This allows labeled fields inside optional groups to be made nullable.
    /// Only collects TokenRefIR and AlternationIR (token choices) — not rule refs
    /// or sequences, which are already handled by other nullable logic.
    /// </summary>
    private static void CollectExpressionsInsideOptional(ExpressionIR expr, bool insideOpt, HashSet<ExpressionIR> result)
    {
        if(insideOpt && (expr is TokenRefIR || expr is AlternationIR))
        {
            _ = result.Add(expr);
        }

        switch(expr)
        {
            case SequenceIR seq:
                foreach(var elem in seq.Elements)
                {
                    CollectExpressionsInsideOptional(elem, insideOpt, result);
                }

                break;
            case AlternationIR alt:
                foreach(var a in alt.Alternatives)
                {
                    CollectExpressionsInsideOptional(a, insideOpt, result);
                }

                break;
            case OptionalIR opt:
                CollectExpressionsInsideOptional(opt.Inner, true, result);
                break;
            case ZeroOrMoreIR zom:
                CollectExpressionsInsideOptional(zom.Inner, insideOpt, result);
                break;
            case OneOrMoreIR oom:
                CollectExpressionsInsideOptional(oom.Inner, insideOpt, result);
                break;
        }
    }

    /// <summary>
    /// Recursively walks the expression tree and adds every <see cref="AlternationIR"/>
    /// nested inside a <see cref="ZeroOrMoreIR"/> or <see cref="OneOrMoreIR"/> to the
    /// <paramref name="result"/> set. A label on a pure-token alternation collected
    /// here -- e.g. <c>op:(PLUS | MINUS)</c> in <c>(op:(PLUS | MINUS))*</c> -- is the
    /// sole value-bearing element of its group (so the group is not struct-projected),
    /// and is promoted to an <c>ImmutableArray&lt;Token&gt;</c> property on the parent
    /// node rather than being silently flattened to a scalar <c>Token</c> that drops
    /// the repetition (design Property 5, Requirement 2.2). The pure-token gate is
    /// applied at the call site via <see cref="IsPureTokenAlternation"/>, so a mixed
    /// alternation is left with its existing scalar promotion. Alternations inside a
    /// two-or-more value-bearing group never reach this promotion: their labels are
    /// excluded up front via <c>inGroupLabels</c> and handled by struct projection.
    /// </summary>
    private static void CollectAlternationsInsideRepetition(ExpressionIR expr, bool insideRep, HashSet<ExpressionIR> result)
    {
        if(insideRep && expr is AlternationIR)
        {
            _ = result.Add(expr);
        }

        switch(expr)
        {
            case SequenceIR seq:
                foreach(var elem in seq.Elements)
                {
                    CollectAlternationsInsideRepetition(elem, insideRep, result);
                }

                break;
            case AlternationIR alt:
                foreach(var a in alt.Alternatives)
                {
                    CollectAlternationsInsideRepetition(a, insideRep, result);
                }

                break;
            case OptionalIR opt:
                CollectAlternationsInsideRepetition(opt.Inner, insideRep, result);
                break;
            case ZeroOrMoreIR zom:
                CollectAlternationsInsideRepetition(zom.Inner, true, result);
                break;
            case OneOrMoreIR oom:
                CollectAlternationsInsideRepetition(oom.Inner, true, result);
                break;
        }
    }

    internal static RuleRefIR? RepeatedRuleRef(ExpressionIR repetitionInner)
    {
        return repetitionInner switch
        {
            RuleRefIR ruleRef => ruleRef,
            SequenceIR sequence => sequence.Elements.OfType<RuleRefIR>().FirstOrDefault(),
            _ => null,
        };
    }

    private static void CollectRepeatedRuleRefs(ExpressionIR expr, HashSet<RuleRefIR> result)
    {
        switch(expr)
        {
            case SequenceIR sequence:
                foreach(var element in sequence.Elements)
                {
                    CollectRepeatedRuleRefs(element, result);
                }

                break;
            case AlternationIR alternation:
                foreach(var alternative in alternation.Alternatives)
                {
                    CollectRepeatedRuleRefs(alternative, result);
                }

                break;
            case OptionalIR optional:
                CollectRepeatedRuleRefs(optional.Inner, result);
                break;
            case ZeroOrMoreIR zeroOrMore:
                AddRepeatedRuleRef(zeroOrMore.Inner, result);
                CollectRepeatedRuleRefs(zeroOrMore.Inner, result);
                break;
            case OneOrMoreIR oneOrMore:
                AddRepeatedRuleRef(oneOrMore.Inner, result);
                CollectRepeatedRuleRefs(oneOrMore.Inner, result);
                break;
        }
    }

    private static void AddRepeatedRuleRef(ExpressionIR repetitionInner, HashSet<RuleRefIR> result)
    {
        if(RepeatedRuleRef(repetitionInner) is { } repeated)
        {
            _ = result.Add(repeated);
        }
    }

    /// <summary>
    /// Walks an expression to find elements that don't have field labels
    /// and generates auto-named properties for them. Repetition/optional wrappers
    /// whose inner sequence became an anonymous group (listed in
    /// <paramref name="groupSequences"/>) are skipped so their projected
    /// <c>Group{N}</c> property is not shadowed by a duplicate auto-generated one.
    /// </summary>
    private static void CollectUnlabeledProperties(
        ExpressionIR expr,
        IReadOnlyList<FieldLabelIR> labels,
        List<PropertyInfo> properties,
        HashSet<string> usedNames,
        HashSet<ExpressionIR> groupSequences)
    {
        // Skip expressions that are already covered by field labels
        if(labels.Any(l => ReferenceEquals(l.Expression, expr)))
        {
            CollectNestedProperties(expr, labels, properties, usedNames, groupSequences, repeated: false, fed: null);
            return;
        }

        switch(expr)
        {
            case SequenceIR seq:
                foreach(var element in seq.Elements)
                {
                    CollectUnlabeledProperties(element, labels, properties, usedNames, groupSequences);
                }

                break;

            case TokenRefIR tokenRef:
                if(!labels.Any(l => ReferenceEquals(l.Expression, expr)))
                {
                    var propName = PascalCase(tokenRef.Token.Name);
                    propName = EnsureUnique(propName, usedNames);
                    properties.Add(new PropertyInfo(propName, "Token", false, false, false, " = default;").FilledBy(tokenRef, false));
                }

                break;

            case RuleRefIR ruleRef:
                if(!labels.Any(l => ReferenceEquals(l.Expression, expr)))
                {
                    var propName = PascalCase(ruleRef.Rule.Name);
                    propName = EnsureUnique(propName, usedNames);
                    var typeName = ruleRef.Rule.Name + "Node";
                    properties.Add(new PropertyInfo(propName, typeName, false, true, false, " = default!;").FilledBy(ruleRef, false));
                }

                break;

            case OptionalIR opt:
                // The inner expression became an anonymous group — its Group{N}
                // property is emitted separately; do not also auto-generate one.
                if(groupSequences.Contains(opt.Inner))
                {
                    break;
                }

                // The inner expression becomes nullable
                var optProp = GetPropertyInfoForOptional(opt.Inner, usedNames, labels);
                if(optProp != null && !labels.Any(l => ReferenceEquals(l.Expression, opt)))
                {
                    properties.Add(optProp);
                }

                CollectNestedProperties(opt.Inner, labels, properties, usedNames, groupSequences, repeated: false, fed: optProp?.Source);
                break;

            case ZeroOrMoreIR zom:
                if(groupSequences.Contains(zom.Inner))
                {
                    break;
                }

                var zomProp = GetPropertyInfoForList(zom.Inner, usedNames);
                if(zomProp != null && !labels.Any(l => ReferenceEquals(l.Expression, zom)))
                {
                    properties.Add(zomProp);
                }

                CollectNestedProperties(zom.Inner, labels, properties, usedNames, groupSequences, repeated: true, fed: zomProp?.Source);
                break;

            case OneOrMoreIR oom:
                if(groupSequences.Contains(oom.Inner))
                {
                    break;
                }

                var oomProp = GetPropertyInfoForList(oom.Inner, usedNames);
                if(oomProp != null && !labels.Any(l => ReferenceEquals(l.Expression, oom)))
                {
                    properties.Add(oomProp);
                }

                CollectNestedProperties(oom.Inner, labels, properties, usedNames, groupSequences, repeated: true, fed: oomProp?.Source);
                break;

            case AlternationIR alt:
                // For unlabeled alternations at non-top level, we don't auto-generate properties
                break;

            default:
                break;
        }
    }

    private static PropertyInfo GetPropertyInfo(ExpressionIR expr, string propName)
    {
        return expr switch
        {
            TokenRefIR => new PropertyInfo(propName, "Token", false, false, false, " = default;"),
            RuleRefIR ruleRef => new PropertyInfo(propName, ruleRef.Rule.Name + "Node", false, true, false, " = default!;"),
            OptionalIR opt => GetPropertyInfoForOptionalInner(opt.Inner, propName),
            ZeroOrMoreIR zom => GetPropertyInfoForListInner(zom.Inner, propName),
            OneOrMoreIR oom => GetPropertyInfoForListInner(oom.Inner, propName),
            // Any choice reaching here is between tokens: UnemittableShapes refuses the rest.
            _ => new PropertyInfo(propName, "Token", false, false, false, " = default;"),
        };
    }

    private static PropertyInfo? GetPropertyInfoForOptional(ExpressionIR inner, HashSet<string> usedNames, IReadOnlyList<FieldLabelIR> labels)
    {
        switch(inner)
        {
            case TokenRefIR tokenRef:
                {
                    var name = EnsureUnique(PascalCase(tokenRef.Token.Name), usedNames);
                    return new PropertyInfo(name, "Token?", true, false, false, "").FilledBy(tokenRef, false);
                }
            case RuleRefIR ruleRef:
                {
                    var name = EnsureUnique(PascalCase(ruleRef.Rule.Name), usedNames);
                    return new PropertyInfo(name, ruleRef.Rule.Name + "Node?", true, true, false, "").FilledBy(ruleRef, false, FindLabel(ruleRef, labels) == null);
                }
            case SequenceIR seq:
                {
                    var seqRuleRef = seq.Elements.OfType<RuleRefIR>().FirstOrDefault();
                    if(seqRuleRef != null)
                    {
                        var name = EnsureUnique(PascalCase(seqRuleRef.Rule.Name), usedNames);
                        return new PropertyInfo(name, seqRuleRef.Rule.Name + "Node?", true, true, false, "").FilledBy(seqRuleRef, false, FindLabel(seqRuleRef, labels) == null);
                    }

                    var seqTokenRef = seq.Elements.OfType<TokenRefIR>().LastOrDefault();
                    if(seqTokenRef != null)
                    {
                        var name = EnsureUnique(PascalCase(seqTokenRef.Token.Name), usedNames);
                        return new PropertyInfo(name, "Token?", true, false, false, "").FilledBy(seqTokenRef, false);
                    }

                    return null;
                }
            default:
                return null;
        }
    }

    private static PropertyInfo GetPropertyInfoForOptionalInner(ExpressionIR inner, string propName)
    {
        return inner switch
        {
            TokenRefIR => new PropertyInfo(propName, "Token?", true, false, false, ""),
            RuleRefIR ruleRef => new PropertyInfo(propName, ruleRef.Rule.Name + "Node?", true, true, false, ""),
            SequenceIR seq => GetPropertyInfoForOptionalSequence(seq, propName),
            _ => new PropertyInfo(propName, "Token?", true, false, false, ""),
        };
    }

    private static PropertyInfo GetPropertyInfoForOptionalSequence(SequenceIR seq, string propName)
    {
        var seqRuleRef = seq.Elements.OfType<RuleRefIR>().FirstOrDefault();
        if(seqRuleRef != null)
        {
            return new PropertyInfo(propName, seqRuleRef.Rule.Name + "Node?", true, true, false, "");
        }

        return new PropertyInfo(propName, "Token?", true, false, false, "");
    }

    private static PropertyInfo? GetPropertyInfoForList(ExpressionIR inner, HashSet<string> usedNames)
    {
        switch(inner)
        {
            case TokenRefIR tokenRef:
                {
                    var name = EnsureUnique(PascalCase(tokenRef.Token.Name) + "s", usedNames);
                    return new PropertyInfo(name, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;").FilledBy(tokenRef, true);
                }
            case RuleRefIR ruleRef:
                {
                    var name = EnsureUnique(PascalCase(ruleRef.Rule.Name) + "s", usedNames);
                    var elementType = ruleRef.Rule.Name + "Node";
                    return new PropertyInfo(name, $"ImmutableArray<{elementType}>", false, true, true, $" = ImmutableArray<{elementType}>.Empty;").FilledBy(ruleRef, true);
                }
            case SequenceIR seq:
                {
                    var seqRuleRef = seq.Elements.OfType<RuleRefIR>().FirstOrDefault();
                    if(seqRuleRef != null)
                    {
                        var name = EnsureUnique(PascalCase(seqRuleRef.Rule.Name) + "s", usedNames);
                        var elementType = seqRuleRef.Rule.Name + "Node";
                        return new PropertyInfo(name, $"ImmutableArray<{elementType}>", false, true, true, $" = ImmutableArray<{elementType}>.Empty;").FilledBy(seqRuleRef, true);
                    }

                    var seqTokenRef = seq.Elements.OfType<TokenRefIR>().LastOrDefault();
                    if(seqTokenRef != null)
                    {
                        var name = EnsureUnique(PascalCase(seqTokenRef.Token.Name) + "s", usedNames);
                        return new PropertyInfo(name, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;").FilledBy(seqTokenRef, true);
                    }

                    return null;
                }
            default:
                return null;
        }
    }

    private static PropertyInfo GetPropertyInfoForListInner(ExpressionIR inner, string propName)
    {
        switch(inner)
        {
            case TokenRefIR:
                return new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
            case RuleRefIR ruleRef:
                {
                    var elementType = ruleRef.Rule.Name + "Node";
                    return new PropertyInfo(propName, $"ImmutableArray<{elementType}>", false, true, true, $" = ImmutableArray<{elementType}>.Empty;");
                }
            case SequenceIR seq:
                {
                    var seqRuleRef = seq.Elements.OfType<RuleRefIR>().FirstOrDefault();
                    if(seqRuleRef != null)
                    {
                        var elementType = seqRuleRef.Rule.Name + "Node";
                        return new PropertyInfo(propName, $"ImmutableArray<{elementType}>", false, true, true, $" = ImmutableArray<{elementType}>.Empty;");
                    }

                    return new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
                }
            default:
                return new PropertyInfo(propName, "ImmutableArray<Token>", false, false, true, " = ImmutableArray<Token>.Empty;");
        }
    }

    private static string PascalCase(string name)
    {
        return string.IsNullOrEmpty(name) ? "Value" : char.ToUpperInvariant(name[0]) + name.Substring(1);
    }

    private static string EnsureUnique(string name, HashSet<string> usedNames)
    {
        var candidate = name;
        var suffix = 2;
        while(!usedNames.Add(candidate))
        {
            candidate = name + suffix;
            suffix++;
        }

        return candidate;
    }

    /// <summary>
    /// Emits a C# interface for a single trait declaration.
    /// The interface is named <c>I{TraitName}Node</c> and contains get-only properties
    /// for each field declared on the trait. When the trait composes other traits,
    /// the emitted interface extends the composed trait interfaces.
    /// </summary>
    private static void EmitTraitInterface(CodeWriter writer, TraitIR trait)
    {
        var interfaceName = $"I{trait.Name}Node";

        // Build base interface list from composed traits
        var baseInterfaces = trait.ComposedTraits
            .Select(ct => $"I{ct.Name}Node")
            .ToList();

        var declaration = baseInterfaces.Count > 0
            ? $"public interface {interfaceName} : {string.Join(", ", baseInterfaces)}"
            : $"public interface {interfaceName}";

        writer.WriteBlock(declaration, () =>
        {
            // Only emit properties for this trait's own fields (not composed)
            foreach(var field in trait.Fields)
            {
                var propType = GetTraitPropertyType(field);
                var propName = PascalCase(field.FieldName);
                writer.WriteLine($"{propType} {propName} {{ get; }}");
            }
        });
    }

    /// <summary>
    /// Returns the C# property type for a trait field, based on whether it is a token
    /// or a rule reference and its cardinality.
    /// </summary>
    private static string GetTraitPropertyType(TraitFieldIR field)
    {
        if(field.IsToken)
        {
            return field.Cardinality switch
            {
                StormFieldCardinality.Optional => "Token?",
                StormFieldCardinality.ZeroOrMore => "ImmutableArray<Token>",
                StormFieldCardinality.OneOrMore => "ImmutableArray<Token>",
                _ => "Token"
            };
        }

        var nodeType = field.TypeName + "Node";
        return field.Cardinality switch
        {
            StormFieldCardinality.Optional => $"{nodeType}?",
            StormFieldCardinality.ZeroOrMore => $"ImmutableArray<{nodeType}>",
            StormFieldCardinality.OneOrMore => $"ImmutableArray<{nodeType}>",
            _ => nodeType
        };
    }

    /// <summary>
    /// Describes a property on a generated AST node type.
    /// </summary>
    private sealed class PropertyInfo
    {
        public string Name { get; set; }
        public string TypeName { get; }
        public bool IsNullable { get; }
        public bool IsNodeType { get; }
        public bool IsList { get; }
        public string DefaultValue { get; }

        public GroupStructModel? Group { get; }

        public bool IsChild { get; private set; } = true;

        public bool MayBeAbsent { get; set; }

        public ExpressionIR? Source { get; private set; }

        public bool Appends { get; private set; }

        public PropertyInfo(string name, string typeName, bool isNullable, bool isNodeType, bool isList, string defaultValue, GroupStructModel? group = null)
        {
            Name = name;
            TypeName = typeName;
            IsNullable = isNullable;
            IsNodeType = isNodeType;
            IsList = isList;
            DefaultValue = defaultValue;
            Group = group;
        }

        public PropertyInfo FilledBy(ExpressionIR? source, bool appends, bool child = true)
        {
            Source = source;
            Appends = appends;
            IsChild = child;
            return this;
        }
    }
