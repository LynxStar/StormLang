using System.Collections.Generic;
using System.Linq;
using System.Text;
using Storm.SourceGenerator.IR;

namespace Storm.SourceGenerator.Emit;

/// <summary>
/// Emits the TokenKind enum and a DFA-based table-driven lexer class for the consumer grammar.
/// The generated lexer uses precomputed transition tables and a maximal-munch loop
/// instead of per-token TryMatch methods.
/// </summary>
public static class LexerEmitter
{
    public static string Emit(EmissionContext context)
    {
        var writer = new CodeWriter();

        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteEmptyLine();
        writer.WriteLine("using System;");
        writer.WriteLine("using System.Collections.Immutable;");
        writer.WriteLine("using Storm.Runtime;");
        writer.WriteEmptyLine();

        writer.WriteBlock($"namespace {context.ConsumerNamespace}", () =>
        {
            EmitTokenKindEnum(writer, context);
            writer.WriteEmptyLine();
            EmitDfaLexerClass(writer, context);
        });

        return writer.ToString();
    }

    // ── TokenKind enum ───────────────────────────────────────────────

    private static void EmitTokenKindEnum(CodeWriter writer, EmissionContext context)
    {
        writer.WriteBlock("public enum TokenKind", () =>
        {
            foreach(var token in context.Grammar.Tokens.OrderBy(t => t.DeclarationIndex))
            {
                writer.WriteLine($"{SanitizeIdentifier(token.Name)},");
            }

            writer.WriteLine("EndOfFile,");
            writer.WriteLine("Error,");
        });
    }

    // ── DFA Lexer Class (replaces old per-token EmitLexerClass) ─────

    /// <summary>
    /// Orchestrates the full DFA pipeline per mode and emits the lexer class:
    /// NFA build → subset construction → minimization → equivalence classes → code emission.
    /// </summary>
    private static void EmitDfaLexerClass(CodeWriter writer, EmissionContext context)
    {
        var className = context.GrammarName + "Lexer";
        var tokens = context.Grammar.Tokens.OrderBy(t => t.DeclarationIndex).ToList();
        var modes = context.Grammar.Modes;

        // Build mode index map
        var modeIndexMap = new Dictionary<string, int>();
        for(var i = 0; i < modes.Count; i++)
        {
            modeIndexMap[modes[i]] = i;
        }

        // Group tokens by mode
        var tokensByMode = new Dictionary<string, List<TokenIR>>();
        foreach(var mode in modes)
        {
            tokensByMode[mode] = new List<TokenIR>();
        }

        foreach(var token in tokens)
        {
            var mode = token.Mode;
            if(!tokensByMode.ContainsKey(mode))
            {
                tokensByMode[mode] = new List<TokenIR>();
            }

            tokensByMode[mode].Add(token);
        }

        // Run DFA pipeline per mode
        var nfaBuilder = new NfaBuilder();
        var perModeDfa = new Dictionary<string, Dfa>();
        var perModeCharToClass = new Dictionary<string, int[]>();
        var perModeClassCount = new Dictionary<string, int>();

        // We share a single equivalence class mapping across all modes
        // by computing it from the union of all mode DFAs.
        // Actually, per the design, each mode gets its own tables.
        // But the equivalence class mapping is shared (one _charClass array).
        // We need to compute a unified equivalence class mapping that works
        // for all modes. The simplest approach: compute per-mode DFAs first,
        // then compute a unified equivalence class from all DFAs combined.

        foreach(var mode in modes)
        {
            var modeTokens = tokensByMode[mode];
            if(modeTokens.Count == 0)
            {
                // Empty mode: create a trivial DFA with just a start state
                var emptyState = new DfaState(0);
                perModeDfa[mode] = new Dfa(0, new List<DfaState> { emptyState });
                continue;
            }

            var combinedNfa = nfaBuilder.BuildCombined(modeTokens);
            var dfa = SubsetConstructor.Convert(combinedNfa);
            var minimizedDfa = DfaMinimizer.Minimize(dfa);
            perModeDfa[mode] = minimizedDfa;
        }

        // Compute unified equivalence classes across all mode DFAs
        var (charToClass, classCount) = ComputeUnifiedEquivalenceClasses(perModeDfa, modes);

        // Build per-mode transition and accepting tables using the unified equivalence classes
        var perModeTransTable = new Dictionary<string, short[,]>();
        var perModeAcceptTable = new Dictionary<string, short[]>();

        foreach(var mode in modes)
        {
            var dfa = perModeDfa[mode];
            var (transTable, acceptTable) = BuildModeTables(dfa, charToClass, classCount);
            perModeTransTable[mode] = transTable;
            perModeAcceptTable[mode] = acceptTable;
        }

        writer.WriteBlock($"public static class {className}", () =>
        {
            // Emit equivalence class mapping array
            EmitCharClassArray(writer, charToClass);
            writer.WriteEmptyLine();

            // Emit per-mode transition and accepting tables
            foreach(var mode in modes)
            {
                var modeName = SanitizeIdentifier(mode);
                var dfa = perModeDfa[mode];
                EmitTransitionTable(writer, modeName, perModeTransTable[mode], dfa.States.Count, classCount);
                writer.WriteEmptyLine();
                EmitAcceptingTable(writer, modeName, perModeAcceptTable[mode]);
                writer.WriteEmptyLine();
                // Emit start state constant per mode
                writer.WriteLine($"private const int _start_{modeName} = {dfa.StartStateId};");
                writer.WriteEmptyLine();
            }

            // Emit hidden token kinds
            EmitHiddenTokenKinds(writer, context);
            writer.WriteEmptyLine();

            // Emit mode constants
            EmitModeConstants(writer, context);
            writer.WriteEmptyLine();

            // Emit TokenModes array
            EmitTokenModes(writer, context, tokens);
            writer.WriteEmptyLine();

            // Emit Lex method (table-driven with maximal munch)
            EmitDfaLexMethod(writer, tokens, modes);
            writer.WriteEmptyLine();

            // IsHidden helper
            writer.WriteBlock("public static bool IsHidden(int tokenKind)", () => writer.WriteLine("return HiddenKinds.Contains(tokenKind);"));
            writer.WriteEmptyLine();

            // GetTokenMode helper
            EmitGetTokenModeMethod(writer);
        });
    }

    // ── Unified Equivalence Class Computation ───────────────────────

    /// <summary>
    /// Computes a unified equivalence class mapping that works across all mode DFAs.
    /// Characters have the same class only if they have identical transition signatures
    /// in ALL modes.
    /// </summary>
    private static (int[] charToClass, int classCount) ComputeUnifiedEquivalenceClasses(
        Dictionary<string, Dfa> perModeDfa,
        IReadOnlyList<string> modes)
    {
        // Compute per-mode equivalence classes
        var perModeResults = new List<(int[] charToClass, int classCount)>();
        foreach(var mode in modes)
        {
            perModeResults.Add(EquivalenceClassComputer.Compute(perModeDfa[mode]));
        }

        if(perModeResults.Count == 1)
        {
            return perModeResults[0];
        }

        // Combine: two characters are in the same unified class only if they
        // are in the same class in every mode.
        var charToClass = new int[65536];
        var signatureToClass = new Dictionary<string, int>();
        var nextClass = 0;

        var sb = new StringBuilder();
        for(var c = 0; c < 65536; c++)
        {
            _ = sb.Clear();
            for(var m = 0; m < perModeResults.Count; m++)
            {
                if(m > 0)
                {
                    _ = sb.Append(',');
                }

                _ = sb.Append(perModeResults[m].charToClass[c]);
            }

            var key = sb.ToString();

            if(!signatureToClass.TryGetValue(key, out var classIndex))
            {
                classIndex = nextClass++;
                signatureToClass[key] = classIndex;
            }

            charToClass[c] = classIndex;
        }

        return (charToClass, nextClass);
    }

    // ── Build per-mode tables from DFA and unified equivalence classes ──

    private static (short[,] transTable, short[] acceptTable) BuildModeTables(
        Dfa dfa, int[] charToClass, int classCount)
    {
        var stateCount = dfa.States.Count;
        var transTable = new short[stateCount, classCount];
        var acceptTable = new short[stateCount];

        // Initialize all transitions to -1 (no transition)
        for(var s = 0; s < stateCount; s++)
        {
            for(var c = 0; c < classCount; c++)
            {
                transTable[s, c] = -1;
            }
        }

        // Build state ID to index mapping (states may not be contiguous)
        var stateIdToIndex = new Dictionary<int, int>();
        for(var i = 0; i < dfa.States.Count; i++)
        {
            stateIdToIndex[dfa.States[i].Id] = i;
        }

        // Fill transition table
        for(var i = 0; i < dfa.States.Count; i++)
        {
            var state = dfa.States[i];
            var stateIndex = stateIdToIndex[state.Id];

            foreach(var transition in state.Transitions)
            {
                if(!stateIdToIndex.TryGetValue(transition.TargetStateId, out var targetIndex))
                {
                    continue;
                }

                // The DFA transition covers a character range [Lo, Hi].
                // With unified equivalence classes, this range may span multiple
                // equivalence classes. We must set the transition for ALL classes
                // that fall within this range.
                // Optimization: scan through the range and collect distinct classes.
                var seenClasses = new HashSet<int>();
                for(int c = transition.Range.Lo; c <= transition.Range.Hi; c++)
                {
                    var eqClass = charToClass[c];
                    if(seenClasses.Add(eqClass))
                    {
                        transTable[stateIndex, eqClass] = (short)targetIndex;
                    }
                }
            }
        }

        // Fill accepting table
        for(var i = 0; i < dfa.States.Count; i++)
        {
            var state = dfa.States[i];
            var stateIndex = stateIdToIndex[state.Id];
            acceptTable[stateIndex] = (short)state.AcceptingTokenIndex;
        }

        return (transTable, acceptTable);
    }

    // ── Table Emission Methods ──────────────────────────────────────

    /// <summary>
    /// Emits the equivalence class mapping array as a static int[] of size 65536.
    /// </summary>
    private static void EmitCharClassArray(CodeWriter writer, int[] charToClass)
    {
        var sb = new StringBuilder();
        _ = sb.Append("private static readonly int[] _charClass = new int[]");
        _ = sb.Append(" { ");
        for(var i = 0; i < 65536; i++)
        {
            if(i > 0)
            {
                _ = sb.Append(", ");
            }

            _ = sb.Append(charToClass[i]);
        }

        _ = sb.Append(" };");
        writer.WriteLine(sb.ToString());
    }

    /// <summary>
    /// Emits the transition table for a mode as a static 2D short array.
    /// </summary>
    private static void EmitTransitionTable(CodeWriter writer, string modeName, short[,] transTable, int stateCount, int classCount)
    {
        var sb = new StringBuilder();
        _ = sb.Append($"private static readonly short[,] _trans_{modeName} = new short[,]");
        _ = sb.Append(" { ");
        for(var s = 0; s < stateCount; s++)
        {
            if(s > 0)
            {
                _ = sb.Append(", ");
            }

            _ = sb.Append("{ ");
            for(var c = 0; c < classCount; c++)
            {
                if(c > 0)
                {
                    _ = sb.Append(", ");
                }

                _ = sb.Append(transTable[s, c]);
            }

            _ = sb.Append(" }");
        }

        _ = sb.Append(" };");
        writer.WriteLine(sb.ToString());
    }

    /// <summary>
    /// Emits the accepting state table for a mode as a static short array.
    /// </summary>
    private static void EmitAcceptingTable(CodeWriter writer, string modeName, short[] acceptTable)
    {
        var sb = new StringBuilder();
        _ = sb.Append($"private static readonly short[] _accept_{modeName} = new short[]");
        _ = sb.Append(" { ");
        for(var i = 0; i < acceptTable.Length; i++)
        {
            if(i > 0)
            {
                _ = sb.Append(", ");
            }

            _ = sb.Append(acceptTable[i]);
        }

        _ = sb.Append(" };");
        writer.WriteLine(sb.ToString());
    }

    // ── Mode constants and mappings ─────────────────────────────────

    /// <summary>
    /// Emits mode constants: <c>private const int Mode_default = 0;</c>, etc.
    /// </summary>
    private static void EmitModeConstants(CodeWriter writer, EmissionContext context)
    {
        var modes = context.Grammar.Modes;
        for(var i = 0; i < modes.Count; i++)
        {
            var modeName = SanitizeIdentifier(modes[i]);
            writer.WriteLine($"private const int Mode_{modeName} = {i};");
        }
    }

    /// <summary>
    /// Emits the <c>TokenModes</c> array mapping each <c>TokenKind</c> ordinal to its mode index.
    /// </summary>
    private static void EmitTokenModes(CodeWriter writer, EmissionContext context, List<TokenIR> tokens)
    {
        var modes = context.Grammar.Modes;
        var modeIndexMap = new Dictionary<string, int>();
        for(var i = 0; i < modes.Count; i++)
        {
            modeIndexMap[modes[i]] = i;
        }

        var entries = new List<string>();
        foreach(var token in tokens)
        {
            var modeIndex = modeIndexMap.TryGetValue(token.Mode, out var idx) ? idx : 0;
            entries.Add(modeIndex.ToString());
        }

        writer.WriteLine($"private static readonly int[] TokenModes = new int[] {{ {string.Join(", ", entries)} }};");
    }

    // ── GetTokenMode method ─────────────────────────────────────────

    /// <summary>
    /// Emits the <c>GetTokenMode</c> method that maps a token kind to its mode index.
    /// </summary>
    private static void EmitGetTokenModeMethod(CodeWriter writer)
    {
        writer.WriteLine("public static int GetTokenMode(int tokenKind) => TokenModes[tokenKind];");
    }

    // ── DFA Lex method (table-driven with maximal munch) ────────────

    private static void EmitDfaLexMethod(CodeWriter writer, List<TokenIR> tokens, IReadOnlyList<string> modes)
    {
        writer.WriteBlock("public static TokenStream Lex(SourceText source, DiagnosticBag diagnostics)", () =>
        {
            writer.WriteLine("var tokens = ImmutableArray.CreateBuilder<Token>();");
            writer.WriteLine("var input = source.Contents;");
            writer.WriteLine("var pos = 0;");
            writer.WriteLine("var line = 1;");
            writer.WriteLine("var col = 1;");
            writer.WriteLine("var modeStack = new System.Collections.Generic.Stack<int>();");
            writer.WriteLine("modeStack.Push(Mode_default);");
            writer.WriteEmptyLine();

            // Emit local variables for transition/accepting table references
            // These are switched based on the current mode
            EmitModeTableSelectionLocals(writer, modes);
            writer.WriteEmptyLine();

            writer.WriteBlock("while (pos < input.Length)", () =>
            {
                // Select tables based on current mode
                EmitModeTableSelection(writer, modes);
                writer.WriteEmptyLine();

                // DFA scan with maximal munch
                writer.WriteLine("var state = startState;");
                writer.WriteLine("var lastAcceptKind = -1;");
                writer.WriteLine("var lastAcceptPos = pos;");
                writer.WriteLine("var scanPos = pos;");
                writer.WriteEmptyLine();

                // Check initial state for accepting (handles zero-length tokens)
                writer.WriteBlock("if (acceptTable[state] >= 0)", () =>
                {
                    writer.WriteLine("lastAcceptKind = acceptTable[state];");
                    writer.WriteLine("lastAcceptPos = scanPos;");
                });
                writer.WriteEmptyLine();

                writer.WriteBlock("while (scanPos < input.Length)", () =>
                {
                    writer.WriteLine("var ch = input[scanPos];");
                    writer.WriteLine("var cls = _charClass[(int)ch];");
                    writer.WriteLine("var next = transTable[state, cls];");
                    writer.WriteEmptyLine();
                    writer.WriteBlock("if (next < 0)", () => writer.WriteLine("break;"));
                    writer.WriteEmptyLine();
                    writer.WriteLine("state = next;");
                    writer.WriteLine("scanPos++;");
                    writer.WriteEmptyLine();
                    writer.WriteBlock("if (acceptTable[state] >= 0)", () =>
                    {
                        writer.WriteLine("lastAcceptKind = acceptTable[state];");
                        writer.WriteLine("lastAcceptPos = scanPos;");
                    });
                });
                writer.WriteEmptyLine();

                // Emit token or error
                writer.WriteBlock("if (lastAcceptKind >= 0 && lastAcceptPos > pos)", () =>
                {
                    writer.WriteLine("var length = lastAcceptPos - pos;");
                    writer.WriteLine("var span = new SourceSpan(pos, length);");
                    writer.WriteLine("var lexeme = input.Substring(pos, length);");
                    writer.WriteLine("var startPos = new LinePosition(line, col);");

                    // Advance line/col
                    writer.WriteBlock("for (var i = pos; i < lastAcceptPos; i++)", () =>
                    {
                        writer.WriteBlock("if (input[i] == '\\n')", () =>
                        {
                            writer.WriteLine("line++;");
                            writer.WriteLine("col = 1;");
                        });
                        writer.WriteBlock("else", () => writer.WriteLine("col++;"));
                    });

                    writer.WriteLine("var endPos = new LinePosition(line, col);");
                    writer.WriteLine("var channel = IsHidden(lastAcceptKind) ? TokenChannel.Hidden : TokenChannel.Default;");
                    writer.WriteLine("tokens.Add(new Token(lastAcceptKind, span, startPos, endPos, channel, lexeme));");
                    writer.WriteLine("pos = lastAcceptPos;");
                    writer.WriteEmptyLine();

                    // Apply mode push/pop actions after emitting the token
                    EmitModeActions(writer, tokens);
                });
                writer.WriteBlock("else", () =>
                {
                    // Error token: no accepting state seen
                    writer.WriteLine("var ch = input[pos];");
                    writer.WriteLine("var startPos = new LinePosition(line, col);");
                    writer.WriteLine("if (ch == '\\n') { line++; col = 1; } else { col++; }");
                    writer.WriteLine("var endPos = new LinePosition(line, col);");
                    writer.WriteLine("diagnostics.Add($\"Unexpected character '{ch}'\", source.Path, startPos.Line, startPos.Column);");
                    writer.WriteLine("tokens.Add(new Token((int)TokenKind.Error, new SourceSpan(pos, 1), startPos, endPos, TokenChannel.Default, ch.ToString()));");
                    writer.WriteLine("pos++;");
                });
            });
            writer.WriteEmptyLine();

            // EndOfFile token
            writer.WriteLine("var eofPos = new LinePosition(line, col);");
            writer.WriteLine("tokens.Add(new Token((int)TokenKind.EndOfFile, new SourceSpan(pos, 0), eofPos, eofPos, TokenChannel.Default, \"\"));");
            writer.WriteLine("return new TokenStream(source, tokens.ToImmutable());");
        });
    }

    /// <summary>
    /// Emits local variable declarations for the transition table, accepting table,
    /// and start state that will be set based on the current mode.
    /// </summary>
    private static void EmitModeTableSelectionLocals(CodeWriter writer, IReadOnlyList<string> modes)
    {
        // Declare the local variables with initial values from the default mode
        var defaultMode = SanitizeIdentifier(modes[0]);
        writer.WriteLine($"short[,] transTable = _trans_{defaultMode};");
        writer.WriteLine($"short[] acceptTable = _accept_{defaultMode};");
        writer.WriteLine($"int startState = _start_{defaultMode};");
    }

    /// <summary>
    /// Emits the switch statement that selects the correct transition/accepting tables
    /// based on the current mode stack top.
    /// </summary>
    private static void EmitModeTableSelection(CodeWriter writer, IReadOnlyList<string> modes)
    {
        if(modes.Count == 1)
        {
            // Single mode: no need for a switch
            return;
        }

        writer.WriteLine("var currentMode = modeStack.Peek();");
        writer.WriteBlock("switch (currentMode)", () =>
        {
            for(var i = 0; i < modes.Count; i++)
            {
                var modeName = SanitizeIdentifier(modes[i]);
                writer.WriteBlock($"case Mode_{modeName}:", () =>
                {
                    writer.WriteLine($"transTable = _trans_{modeName};");
                    writer.WriteLine($"acceptTable = _accept_{modeName};");
                    writer.WriteLine($"startState = _start_{modeName};");
                    writer.WriteLine("break;");
                });
            }
        });
    }

    /// <summary>
    /// Emits the switch statement that applies push/pop mode actions after a token is matched.
    /// Only emits cases for tokens that have a non-trivial mode action.
    /// </summary>
    private static void EmitModeActions(CodeWriter writer, List<TokenIR> tokens)
    {
        // Check if any tokens have mode actions
        var hasActions = tokens.Any(t => t.ModeAction is PushModeIR or PopModeIR);
        if(!hasActions)
        {
            return;
        }

        writer.WriteBlock("switch (lastAcceptKind)", () =>
        {
            for(var i = 0; i < tokens.Count; i++)
            {
                var token = tokens[i];
                if(token.ModeAction is PushModeIR push)
                {
                    var targetMode = SanitizeIdentifier(push.ModeName);
                    writer.WriteLine($"case {i}: modeStack.Push(Mode_{targetMode}); break;");
                }
                else if(token.ModeAction is PopModeIR)
                {
                    writer.WriteLine($"case {i}: if (modeStack.Count > 1) modeStack.Pop(); break;");
                }
            }
        });
    }

    // ── Hidden token kinds ──────────────────────────────────────────

    private static void EmitHiddenTokenKinds(CodeWriter writer, EmissionContext context)
    {
        var hiddenTokens = context.Grammar.Tokens
            .Where(t => t.IsHidden)
            .OrderBy(t => t.DeclarationIndex)
            .ToList();

        if(hiddenTokens.Count == 0)
        {
            writer.WriteLine("private static System.Collections.Generic.HashSet<int> HiddenKinds = new System.Collections.Generic.HashSet<int>();");
            return;
        }

        writer.WriteLine("private static System.Collections.Generic.HashSet<int> HiddenKinds = new System.Collections.Generic.HashSet<int>");
        writer.WriteLine("{");
        writer.Indent();
        foreach(var token in hiddenTokens)
        {
            writer.WriteLine($"(int)TokenKind.{SanitizeIdentifier(token.Name)},");
        }

        writer.Dedent();
        writer.WriteLine("};");
    }

    // ── Utility helpers ─────────────────────────────────────────────

    internal static string EscapeStringForCSharp(string value)
    {
        return value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\n", "\\n")
            .Replace("\r", "\\r")
            .Replace("\t", "\\t");
    }

    /// <summary>
    /// Escapes a string for use inside a C# verbatim string literal (@"...").
    /// The only character that needs escaping is the double-quote, which is
    /// doubled ("") inside a verbatim string.
    /// </summary>
    internal static string EscapeForVerbatimString(string value)
    {
        return value.Replace("\"", "\"\"");
    }

    internal static string SanitizeIdentifier(string name)
    {
        if(string.IsNullOrEmpty(name))
        {
            return "_";
        }

        var sb = new StringBuilder();
        for(var i = 0; i < name.Length; i++)
        {
            var c = name[i];
            _ = char.IsLetterOrDigit(c) || c == '_' ? sb.Append(c) : sb.Append('_');
        }

        if(sb.Length > 0 && char.IsDigit(sb[0]))
        {
            _ = sb.Insert(0, '_');
        }

        return sb.Length == 0 ? "_" : sb.ToString();
    }
