using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis.CSharp;
using Storm.SourceGenerator.IR;

namespace Storm.SourceGenerator.Emit;

public static partial class ParserEmitter
{
    public static string Emit(EmissionContext context)
    {
        var writer = new CodeWriter();

        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable annotations");
        writer.WriteLine("#nullable disable warnings");
        writer.WriteEmptyLine();
        writer.WriteLine("using System;");
        writer.WriteLine("using System.Collections.Generic;");
        writer.WriteLine("using System.Collections.Immutable;");
        writer.WriteLine("using Storm.Runtime;");
        writer.WriteEmptyLine();

        writer.WriteBlock($"namespace {context.ConsumerNamespace}", () => EmitParserClass(writer, context));

        return writer.ToString();
    }

    private static void EmitParserClass(CodeWriter writer, EmissionContext context)
    {
        var className = context.GrammarName + "Parser";

        writer.WriteBlock($"public static class {className}", () =>
        {
            EmitParserState(writer, context);
            writer.WriteEmptyLine();
            EmitHelpers(writer, context);

            foreach(var rule in context.Grammar.Rules)
            {
                writer.WriteEmptyLine();
                EmitPublicParseMethod(writer, rule);
            }

            foreach(var rule in context.Grammar.Rules)
            {
                writer.WriteEmptyLine();
                EmitInternalParseMethod(writer, context, rule);
            }
        });
    }

    private static void EmitParserState(CodeWriter writer, EmissionContext context)
    {
        writer.WriteLine("[ThreadStatic] private static ImmutableArray<Token> _tokens;");
        writer.WriteLine("[ThreadStatic] private static ImmutableArray<Token> _allTokens;");
        writer.WriteLine("[ThreadStatic] private static int _pos;");
        writer.WriteLine("[ThreadStatic] private static bool _hasError;");
        writer.WriteLine("[ThreadStatic] private static DiagnosticBag? _diagnostics;");
        writer.WriteLine("[ThreadStatic] private static string? _sourcePath;");
        writer.WriteLine("[ThreadStatic] private static int[]? _defaultToAllIndex;");

        if(context.Memoization.Count > 0)
        {
            writer.WriteLine("[ThreadStatic] private static Dictionary<long, (SyntaxNode? Node, int End)>? _memo;");
        }

        writer.WriteEmptyLine();
        writer.WriteLine("public static int LastPosition => _pos;");
    }

    private static void EmitHelpers(CodeWriter writer, EmissionContext context)
    {
        writer.WriteBlock("private static void Init(TokenStream ts, DiagnosticBag diag)", () =>
        {
            writer.WriteLine("_tokens = ts.DefaultChannelTokens;");
            writer.WriteLine("_allTokens = ts.AllTokens;");
            writer.WriteLine("_pos = 0;");
            writer.WriteLine("_hasError = false;");
            writer.WriteLine("_diagnostics = diag;");
            writer.WriteLine("_sourcePath = ts.Source.Path;");
            writer.WriteEmptyLine();
            writer.WriteLine("// Build default-channel-index → all-tokens-index mapping for O(1) AttachHidden lookups.");
            writer.WriteLine("_defaultToAllIndex = new int[_tokens.Length];");
            writer.WriteLine("var allIdx = 0;");
            writer.WriteBlock("for (var defIdx = 0; defIdx < _tokens.Length; defIdx++)", () =>
            {
                writer.WriteLine("var target = _tokens[defIdx].Span.Start;");
                writer.WriteBlock("while (allIdx < _allTokens.Length && (_allTokens[allIdx].Span.Start != target || _allTokens[allIdx].Channel != TokenChannel.Default))", () => writer.WriteLine("allIdx++;"));
                writer.WriteLine("_defaultToAllIndex[defIdx] = allIdx;");
                writer.WriteLine("allIdx++;");
            });
            if(context.Memoization.Count > 0)
            {
                writer.WriteLine("_memo = new Dictionary<long, (SyntaxNode?, int)>();");
            }
        });
        writer.WriteEmptyLine();

        writer.WriteBlock("private static int Peek(int offset = 0)", () =>
        {
            writer.WriteLine("var i = _pos + offset;");
            writer.WriteLine($"return i < _tokens.Length ? _tokens[i].Kind : (int)TokenKind.EndOfFile;");
        });
        writer.WriteEmptyLine();

        writer.WriteBlock("private static Token Cur()", () => writer.WriteLine("return _pos < _tokens.Length ? _tokens[_pos] : _tokens[_tokens.Length - 1];"));
        writer.WriteEmptyLine();

        writer.WriteBlock("private static Token Eat()", () =>
        {
            writer.WriteLine("var t = Cur();");
            writer.WriteLine("if (_pos < _tokens.Length) _pos++;");
            writer.WriteLine("return t;");
        });
        writer.WriteEmptyLine();

        writer.WriteBlock("private static Token? Match(int kind)", () =>
        {
            writer.WriteLine("if (_hasError) return null;");
            writer.WriteLine("return Peek() == kind ? Eat() : (Token?)null;");
        });
        writer.WriteEmptyLine();

        writer.WriteBlock("private static Token Require(int kind)", () =>
        {
            writer.WriteLine("if (_hasError) return Cur();");
            writer.WriteLine("var t = Match(kind);");
            writer.WriteBlock("if (t == null)", () =>
            {
                writer.WriteLine("var cur = Cur();");
                writer.WriteLine("_hasError = true;");
                writer.WriteLine("_diagnostics?.Add($\"Expected token kind {kind} but found '{cur.Lexeme}'\", _sourcePath, cur.Start.Line, cur.Start.Column);");
                writer.WriteLine("return cur;");
            });
            writer.WriteLine("return t.Value;");
        });
        writer.WriteEmptyLine();

        writer.WriteBlock("private static void Error(string message)", () => writer.WriteBlock("if (!_hasError)", () =>
            {
                writer.WriteLine("_hasError = true;");
                writer.WriteLine("var cur = Cur();");
                writer.WriteLine("_diagnostics?.Add($\"{message}\", _sourcePath, cur.Start.Line, cur.Start.Column);");
            }));
        writer.WriteEmptyLine();

        writer.WriteBlock("private static SourceSpan Span(int startPos)", () =>
        {
            writer.WriteLine("if (startPos >= _tokens.Length) return new SourceSpan(0, 0);");
            writer.WriteLine("var s = _tokens[startPos].Span;");
            writer.WriteLine("var e = _pos > 0 && _pos - 1 < _tokens.Length ? _tokens[_pos - 1].Span : s;");
            writer.WriteLine("return new SourceSpan(s.Start, Math.Max(0, e.End - s.Start));");
        });
        writer.WriteEmptyLine();

        EmitHiddenTokenHelpers(writer);

        if(context.Memoization.Count > 0)
        {
            writer.WriteEmptyLine();
            writer.WriteLine("private static long MemoKey(int ruleId, int pos) => ((long)ruleId << 32) | (uint)pos;");
        }
    }

    private static void EmitHiddenTokenHelpers(CodeWriter writer)
    {
        writer.WriteBlock("private static T AttachHidden<T>(T node, int startDefaultIdx, int endDefaultIdx) where T : SyntaxNode", () =>
        {
            writer.WriteBlock("if (_allTokens.Length == 0)", () => writer.WriteLine("return node;"));
            writer.WriteEmptyLine();
            writer.WriteLine("// Map default-channel indices to all-tokens indices via pre-built lookup array");
            writer.WriteLine("var allStart = startDefaultIdx < _defaultToAllIndex!.Length ? _defaultToAllIndex[startDefaultIdx] : _allTokens.Length;");
            writer.WriteLine("var allEnd = endDefaultIdx > 0 && endDefaultIdx - 1 < _defaultToAllIndex.Length ? _defaultToAllIndex[endDefaultIdx - 1] : _allTokens.Length - 1;");
            writer.WriteEmptyLine();
            writer.WriteLine("// Leading: hidden tokens before the first default-channel token");
            writer.WriteBlock("if (allStart > 0)", () =>
            {
                writer.WriteLine("var leading = ImmutableArray.CreateBuilder<Token>();");
                writer.WriteBlock("for (var i = allStart - 1; i >= 0; i--)", () =>
                {
                    writer.WriteBlock("if (_allTokens[i].Channel == TokenChannel.Hidden)", () => writer.WriteLine("leading.Insert(0, _allTokens[i]);"));
                    writer.WriteBlock("else", () => writer.WriteLine("break;"));
                });
                writer.WriteBlock("if (leading.Count > 0)", () => writer.WriteLine("node.LeadingHiddenTokens = leading.ToImmutable();"));
            });
            writer.WriteEmptyLine();
            writer.WriteLine("// Trailing: hidden tokens after the last default-channel token");
            writer.WriteBlock("if (allEnd + 1 < _allTokens.Length)", () =>
            {
                writer.WriteLine("var trailing = ImmutableArray.CreateBuilder<Token>();");
                writer.WriteBlock("for (var i = allEnd + 1; i < _allTokens.Length; i++)", () =>
                {
                    writer.WriteBlock("if (_allTokens[i].Channel == TokenChannel.Hidden)", () => writer.WriteLine("trailing.Add(_allTokens[i]);"));
                    writer.WriteBlock("else", () => writer.WriteLine("break;"));
                });
                writer.WriteBlock("if (trailing.Count > 0)", () => writer.WriteLine("node.TrailingHiddenTokens = trailing.ToImmutable();"));
            });
            writer.WriteEmptyLine();
            writer.WriteLine("return node;");
        });
    }

    private static void EmitPublicParseMethod(CodeWriter writer, RuleIR rule)
    {
        var nodeName = rule.Name + "Node";
        var methodName = "Parse" + rule.Name;

        writer.WriteBlock($"public static {nodeName}? {methodName}(TokenStream tokens, DiagnosticBag diagnostics)", () =>
        {
            writer.WriteLine("Init(tokens, diagnostics);");
            writer.WriteLine($"var result = _{methodName}();");
            writer.WriteBlock("if (_hasError)", () => writer.WriteLine("return null;"));
            writer.WriteBlock("if (result != null)", () => writer.WriteLine("result = AttachHidden(result, 0, _pos);"));
            writer.WriteLine("return result;");
        });
    }

    private static void EmitInternalParseMethod(CodeWriter writer, EmissionContext context, RuleIR rule)
    {
        var nodeName = rule.Name + "Node";
        var hasNamedAlts = rule.Alternatives.Any(a => a.AlternativeName != null);

        if(context.Memoization.IsMemoized(rule.Name))
        {
            EmitMemoizedInternalParseMethod(writer, context, rule, nodeName, hasNamedAlts);
            return;
        }

        var methodName = "_Parse" + rule.Name;

        writer.WriteBlock($"private static {nodeName}? {methodName}()", () =>
        {
            writer.WriteLine("if (_hasError) return null;");
            if(rule.Alternatives.Count == 1 && !hasNamedAlts)
            {
                EmitSingleAlt(writer, context, rule, nodeName);
            }
            else
            {
                EmitMultiAlt(writer, context, rule, nodeName, hasNamedAlts);
            }
        });
    }

    private static void EmitMemoizedInternalParseMethod(CodeWriter writer, EmissionContext context, RuleIR rule, string nodeName, bool hasNamedAlts)
    {
        var ruleId = context.Memoization.RuleIds[rule.Name];
        var wrapperName = "_Parse" + rule.Name;
        var bodyName = "_Parse" + rule.Name + "_Body";

        writer.WriteBlock($"private static {nodeName}? {wrapperName}()", () =>
        {
            writer.WriteLine("if (_hasError) return null;");
            writer.WriteEmptyLine();
            writer.WriteLine($"var _key = MemoKey({ruleId}, _pos);");
            writer.WriteBlock("if (_memo!.TryGetValue(_key, out var _hit))", () =>
            {
                writer.WriteLine("_pos = _hit.End;");
                writer.WriteLine($"return ({nodeName}?)_hit.Node;");
            });
            writer.WriteEmptyLine();
            writer.WriteLine("var _entryPos = _pos;");
            writer.WriteLine($"var _result = {bodyName}();");
            // Req 2.6 caches a failure at entry, and a failed single-alternative body does not rewind _pos.
            writer.WriteLine("_memo[_key] = (_result, _result == null ? _entryPos : _pos);");
            writer.WriteLine("return _result;");
        });

        writer.WriteEmptyLine();

        writer.WriteBlock($"private static {nodeName}? {bodyName}()", () =>
        {
            writer.WriteLine("if (_hasError) return null;");
            if(rule.Alternatives.Count == 1 && !hasNamedAlts)
            {
                EmitSingleAlt(writer, context, rule, nodeName);
            }
            else
            {
                EmitMultiAlt(writer, context, rule, nodeName, hasNamedAlts);
            }
        });
    }

    private static void EmitSingleAlt(CodeWriter writer, EmissionContext context, RuleIR rule, string nodeName)
    {
        writer.WriteLine("var sp = _pos;");
        if(rule.Alternatives[0].Expression is not InlineBlockIR)
        {
            writer.WriteLine("var ok = true;");
        }

        EmitAltBodyWithCheck(writer, context, rule, rule.Alternatives[0], nodeName, "sp", "ok");
        writer.WriteLine("return null;");
    }

    private static void EmitMultiAlt(CodeWriter writer, EmissionContext context, RuleIR rule, string nodeName, bool hasNamedAlts)
    {
        writer.WriteLine("var saved = _pos;");
        writer.WriteLine("var savedError = _hasError;");
        writer.WriteLine("var savedDiagCount = _diagnostics?.Count ?? 0;");

        for(var i = 0; i < rule.Alternatives.Count; i++)
        {
            var alt = rule.Alternatives[i];
            var altName = alt.AlternativeName ?? $"Alt{i}";
            var typeName = hasNamedAlts ? ((alt.AlternativeName ?? "Default") + rule.Name + "Node") : nodeName;

            writer.WriteEmptyLine();
            writer.WriteLine($"// Alternative: {altName}");
            writer.WriteLine("_pos = saved;");
            writer.WriteLine("_hasError = false;");
            writer.WriteLine("_diagnostics?.TruncateTo(savedDiagCount);");

            if(alt.Expression is InlineBlockIR inlineBlock)
            {
                writer.WriteLine("{");
                writer.Indent();
                EmitInlineBlock(writer, context, inlineBlock, rule.Name, "saved");
                writer.Dedent();
                writer.WriteLine("}");
            }
            else
            {
                writer.WriteLine("{");
                writer.Indent();
                writer.WriteLine("var sp = _pos;");
                writer.WriteLine("var ok = true;");
                EmitAltBodyWithCheck(writer, context, rule, alt, typeName, "sp", "ok");
                writer.Dedent();
                writer.WriteLine("}");
            }
        }

        writer.WriteEmptyLine();
        writer.WriteLine("_pos = saved;");
        writer.WriteLine("_hasError = savedError;");
        writer.WriteLine("_diagnostics?.TruncateTo(savedDiagCount);");
        writer.WriteLine("return null;");
    }

    private static void EmitAltBodyWithCheck(CodeWriter writer, EmissionContext context, RuleIR rule, RuleAlternativeIR alt, string typeName, string spVar, string okVar)
    {
        if(alt.Expression is InlineBlockIR inlineBlock)
        {
            var ruleName = typeName.EndsWith("Node") ? typeName.Substring(0, typeName.Length - 4) : typeName;
            EmitInlineBlock(writer, context, inlineBlock, ruleName, spVar);
            return;
        }

        var elements = new ElementWriter(writer, context);
        var frame = elements.DeclareNode(AstEmitter.NodeSlots(rule, alt, typeName), alt, typeName);
        elements.Element(alt.Expression, okVar, frame);
        elements.FinishLists(frame);

        writer.WriteBlock($"if ({okVar} && !_hasError)", () =>
        {
            writer.WriteLine($"var node = new {typeName}();");
            if(rule.Alternatives.Count > 1 && rule.Alternatives.All(candidate => candidate.AlternativeName == null && candidate.Expression is not InlineBlockIR))
            {
                writer.WriteLine($"node.__StormAlternative = {rule.Alternatives.ToList().IndexOf(alt)};");
            }

            foreach(var slot in frame.Slots)
            {
                writer.WriteLine($"node.{slot.Target} = {slot.Local};");
            }

            writer.WriteLine($"node.Span = Span({spVar});");
            writer.WriteLine($"node = AttachHidden(node, {spVar}, _pos);");
            writer.WriteLine("return node;");
        });
    }

    private static string MatchExprForAlternative(EmissionContext context, ExpressionIR alternative)
    {
        switch(alternative)
        {
            case TokenRefIR tokenRef:
                return MatchToken(tokenRef);
            case StringLiteralIR lit:
                {
                    var token = FindTokenForLiteral(context, lit.Value);
                    return token != null
                        ? $"Match((int){TokenKindRef(token.Name)})"
                        : "(Token?)null";
                }

            default:
                return "(Token?)null";
        }
    }

    private static string LowerFirst(string name)
    {
        if(string.IsNullOrEmpty(name))
        {
            return name;
        }

        return char.ToLowerInvariant(name[0]) + name.Substring(1);
    }

    private static void EmitPredicate(CodeWriter writer, EmissionContext context, PredicateIR predicate, string? okVar)
    {
        var guard = okVar ?? "true";
        var fail = okVar != null ? $"{okVar} = false;" : "Error(\"Predicate failed\");";
        var offset = 0;
        var tokenTest = TryBuildTokenTest(context, predicate.Inner, ref offset);
        if(tokenTest != null)
        {
            var failed = predicate.IsNegated ? tokenTest : $"!({tokenTest})";
            writer.WriteLine($"if ({guard} && {failed}) {fail}");
            return;
        }

        var rule = ((RuleRefIR)predicate.Inner).Rule.Name;
        writer.WriteBlock($"if ({guard})", () =>
        {
            writer.WriteLine("var _predSaved = _pos;");
            writer.WriteLine("var _predSavedError = _hasError;");
            writer.WriteLine("var _predSavedDiagCount = _diagnostics?.Count ?? 0;");
            writer.WriteLine($"var _predMatched = _Parse{rule}() != null && !_hasError;");
            writer.WriteLine("_pos = _predSaved;");
            writer.WriteLine("_hasError = _predSavedError;");
            writer.WriteLine("_diagnostics?.TruncateTo(_predSavedDiagCount);");
            writer.WriteLine($"if (_predMatched == {(predicate.IsNegated ? "true" : "false")}) {fail}");
        });
    }

    private static string? TryBuildTokenTest(EmissionContext context, ExpressionIR expr, ref int offset)
    {
        switch(expr)
        {
            case TokenRefIR tokenRef:
                return TokenTest(tokenRef, offset++);

            case StringLiteralIR lit:
                var token = FindTokenForLiteral(context, lit.Value);
                return token == null ? null : $"Peek({offset++}) == (int){TokenKindRef(token.Name)}";

            case AlternationIR alternation:
                {
                    var start = offset;
                    var width = -1;
                    var tests = new List<string>();
                    foreach(var alternative in alternation.Alternatives)
                    {
                        var at = start;
                        var test = TryBuildTokenTest(context, alternative, ref at);
                        if(test == null || (width >= 0 && at - start != width))
                        {
                            return null;
                        }

                        width = at - start;
                        tests.Add(test);
                    }

                    offset = start + width;
                    return "(" + string.Join(" || ", tests) + ")";
                }

            case SequenceIR sequence:
                {
                    var tests = new List<string>();
                    foreach(var element in sequence.Elements)
                    {
                        var test = TryBuildTokenTest(context, element, ref offset);
                        if(test == null)
                        {
                            return null;
                        }

                        tests.Add(test);
                    }

                    return "(" + string.Join(" && ", tests) + ")";
                }

            default:
                return null;
        }
    }

    private static TokenIR? FindTokenForLiteral(EmissionContext context, string value)
    {
        foreach(var token in context.Grammar.Tokens)
        {
            if(token.Expression is StringLiteralIR lit && lit.Value == value)
            {
                return token;
            }
        }

        return null;
    }

    private static string MatchToken(TokenRefIR tokenRef)
    {
        var kind = TokenKindRef(tokenRef.Token.Name);
        var match = $"Match((int){kind})";
        return tokenRef.Text == null
            ? match
            : $"(Peek() == (int){kind} && Cur().Lexeme == {SymbolDisplay.FormatLiteral(tokenRef.Text, quote: true)} ? {match} : (Token?)null)";
    }

    private static string TokenTest(TokenRefIR tokenRef, int offset)
    {
        var test = $"Peek({offset}) == (int){TokenKindRef(tokenRef.Token.Name)}";
        return tokenRef.Text == null
            ? test
            : $"({test} && _tokens[_pos + {offset}].Lexeme == {SymbolDisplay.FormatLiteral(tokenRef.Text, quote: true)})";
    }

    private static string TokenKindRef(string tokenName)
    {
        return "TokenKind." + LexerEmitter.SanitizeIdentifier(tokenName);
    }

    private static string PascalCase(string name)
    {
        if(string.IsNullOrEmpty(name))
        {
            return name;
        }

        return char.ToUpperInvariant(name[0]) + name.Substring(1);
    }
}